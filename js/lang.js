function standardizeTraditionalChineseDictionary(dictionary) {
    var terminology = [
        ["項目", "專案"], ["數據", "資料"], ["消息", "訊息"], ["用戶", "使用者"],
        ["服務器", "伺服器"], ["鏈接", "連結"], ["加載", "載入"], ["組件", "元件"],
        ["代碼", "程式碼"], ["視圖", "檢視"], ["運行", "執行"], ["設置", "設定"],
        ["保存", "儲存"], ["文本", "文字"], ["視頻", "影片"], ["攝像頭", "攝影機"],
        ["登錄", "登入"], ["訪問", "存取"], ["復製", "複製"], ["控製", "控制"],
        ["標簽", "標籤"], ["觸髮", "觸發"], ["限製", "限制"], ["字符", "字元"],
        ["布局", "版面配置"], ["編程", "程式設計"], ["當前", "目前"], ["信息", "資訊"],
        ["清空", "清除"], ["添加", "新增"], ["創建", "建立"], ["導入", "匯入"],
        ["發送", "傳送"], ["采集", "蒐集"], ["實時", "即時"], ["郵箱", "電子郵件"]
    ];
    Object.keys(dictionary).forEach(function (key) {
        if (typeof dictionary[key] !== "string") return;
        terminology.forEach(function (pair) {
            dictionary[key] = dictionary[key].split(pair[0]).join(pair[1]);
        });
    });
}

