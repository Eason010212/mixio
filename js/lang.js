function translateElement(element) {
    var key = element.getAttribute("key") || element.getAttribute("data-i18n");
    if (!key) return;
    var value = String(getTranslationEntry(key));
    var parts = value.split("$");
    if (parts.length > 1) {
        element.setAttribute(parts[0], parts.slice(1).join("$"));
    } else if ((element.tagName === "INPUT" || element.tagName === "TEXTAREA") && element.hasAttribute("placeholder")) {
        element.setAttribute("placeholder", value);
    } else {
        element.textContent = value;
    }
}

function applyTranslations(root) {
    if (typeof document === "undefined") return;
    var scope = root && root.querySelectorAll ? root : document;
    if (scope.matches && scope.matches(".lang,[data-i18n]")) translateElement(scope);
    Array.prototype.forEach.call(scope.querySelectorAll(".lang,[data-i18n]"), translateElement);
    document.documentElement.setAttribute("lang", lang === "tw" ? "zh-Hant" : (lang === "zh" ? "zh-Hans" : "en"));
}

function setCorrectButtonStatus() {
    if (typeof $ === "undefined") return;
    $(".translate").removeClass("btn-primary").addClass("btn-secondary");
    $("#" + lang).removeClass("btn-secondary").addClass("btn-primary");
}

function setLanguage(languageCode, persist) {
    lang = normalizeLanguage(languageCode);
    if (persist !== false && typeof localStorage !== "undefined") {
        try { localStorage.setItem("lang", lang); } catch (e) { /* Storage may be disabled. */ }
    }
    applyTranslations();
    setCorrectButtonStatus();
    if (typeof window !== "undefined" && typeof window.CustomEvent === "function") {
        window.dispatchEvent(new CustomEvent("mixio:languagechange", { detail: { lang: lang } }));
    }
    return lang;
}

