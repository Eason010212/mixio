function normalizeLanguage(languageCode) {
    var code = String(languageCode || "").replace("_", "-").toLowerCase();
    if (code === "tw" || code === "zh-tw" || code === "zh-hk" || code === "zh-mo" || code.indexOf("zh-hant") === 0) return "tw";
    if (code === "zh" || code.indexOf("zh-") === 0) return "zh";
    return code === "en" || code.indexOf("en-") === 0 ? "en" : "en";
}

function getTranslationEntry(key, languageCode) {
    var code = normalizeLanguage(languageCode || lang);
    if (JSLang[code] && Object.prototype.hasOwnProperty.call(JSLang[code], key)) return JSLang[code][key];
    if (arrLang[code] && Object.prototype.hasOwnProperty.call(arrLang[code], key)) return arrLang[code][key];
    if (JSLang.en && Object.prototype.hasOwnProperty.call(JSLang.en, key)) return JSLang.en[key];
    if (arrLang.en && Object.prototype.hasOwnProperty.call(arrLang.en, key)) return arrLang.en[key];
    return key;
}

function i18n(key, params, languageCode) {
    var value = String(getTranslationEntry(key, languageCode));
    var attributeSeparator = value.indexOf("$");
    if (attributeSeparator > 0) value = value.slice(attributeSeparator + 1);
    Object.keys(params || {}).forEach(function (paramKey) {
        value = value.split("{{" + paramKey + "}}").join(String(params[paramKey]));
    });
    return value;
}

